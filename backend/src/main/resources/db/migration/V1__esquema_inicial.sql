-- Esquema inicial de Punto Espresso.
-- Es una copia fiel del esquema que Hibernate había creado en Supabase. En la base de producción
-- esta versión se marca como ya aplicada (baseline); solo se ejecuta al crear una base nueva.

create table categorias (
    id_categoria integer generated by default as identity,
    nombre       varchar(255),
    constraint categorias_pkey primary key (id_categoria)
);

create table clientes (
    id_cliente integer generated by default as identity,
    contrasena varchar(255),
    dni        varchar(255),
    email      varchar(255),
    nombre     varchar(255),
    telefono   varchar(255),
    constraint clientes_pkey primary key (id_cliente)
);

create unique index uq_clientes_dni on clientes (dni);

create table sedes (
    id_sede       integer generated by default as identity,
    direccion     varchar(255),
    horario_dias  varchar(255),
    horario_horas varchar(255),
    nombre        varchar(255),
    constraint sedes_pkey primary key (id_sede)
);

create table usuarios_sistema (
    id_usuario_sistema integer generated by default as identity,
    contrasena         varchar(255),
    email              varchar(255),
    nombre             varchar(255),
    rol                varchar(255),
    constraint usuarios_sistema_pkey primary key (id_usuario_sistema)
);

create table direcciones (
    id_direccion integer generated by default as identity,
    alias        varchar(255),
    direccion    varchar(255),
    id_cliente   integer,
    constraint direcciones_pkey primary key (id_direccion),
    constraint fke32spd6mjtedm9iolngn2uk7g foreign key (id_cliente) references clientes (id_cliente)
);

create table productos (
    id_producto        integer generated by default as identity,
    descripcion        varchar(255),
    imagen             varchar(255),
    nombre             varchar(255),
    precio             numeric(10,2) not null,
    stock              integer not null,
    id_categoria       integer,
    id_usuario_sistema integer,
    constraint productos_pkey primary key (id_producto),
    constraint fkdtoa37luoxhhvbicrfiu5ygbj foreign key (id_categoria) references categorias (id_categoria),
    constraint fkh0r42iunjvxjejci71ih9s5fg foreign key (id_usuario_sistema) references usuarios_sistema (id_usuario_sistema)
);

create table ordenes (
    id_orden           integer generated by default as identity,
    codigo_unico       varchar(255),
    estado             varchar(255),
    metodo_pago        varchar(255),
    tipo_entrega       varchar(255),
    total              numeric(12,2) not null,
    id_cliente         integer,
    id_direccion       integer,
    id_sede            integer,
    id_usuario_sistema integer,
    fecha_creacion     timestamp(6),
    constraint ordenes_pkey primary key (id_orden),
    constraint fkmytf7ma2ikyrbrbjke3649qml foreign key (id_cliente) references clientes (id_cliente),
    constraint fk431cqk3ob4ahlvwtd6cqtkn1u foreign key (id_direccion) references direcciones (id_direccion),
    constraint fkabjn44hy056rnivghey3x9kiw foreign key (id_sede) references sedes (id_sede),
    constraint fkmk9brtd02elf83j2uiksyw3jd foreign key (id_usuario_sistema) references usuarios_sistema (id_usuario_sistema)
);

create table orden_detalle (
    id_orden_detalle integer generated by default as identity,
    cantidad         integer not null,
    instrucciones    varchar(255),
    precio_unitario  numeric(10,2) not null,
    id_orden         integer,
    id_producto      integer,
    constraint orden_detalle_pkey primary key (id_orden_detalle),
    constraint fkoau5c5wkd94f3mehy8h4rcb1i foreign key (id_orden) references ordenes (id_orden),
    constraint fk1tw1wjxyhil7wmumwvh978x4w foreign key (id_producto) references productos (id_producto)
);